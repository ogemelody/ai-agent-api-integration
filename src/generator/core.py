from pathlib import Path

def generate(name: str, output: Path) -> list[Path]:
    if not name.isidentifier():
        raise ValueError("name must be a valid Swift identifier")
    app_dir = output / name
    app_dir.mkdir(parents=True, exist_ok=True)
    files = {
        f"{name}App.swift": f"import SwiftUI\n\n@main\nstruct {name}App: App {{\n    var body: some Scene {{\n        WindowGroup {{ ContentView() }}\n    }}\n}}\n",
        "ContentView.swift": 'import SwiftUI\n\nstruct ContentView: View {\n    var body: some View {\n        VStack {\n            Image(systemName: "message")\n            Text("Generated by the iMessage AI Agent")\n        }\n        .padding()\n    }\n}\n\n#Preview { ContentView() }\n',
        "project.yml": (f"name: {name}\n"
            "options:\n  bundleIdPrefix: com.imessageagent\n"
            "settings:\n  base:\n    SWIFT_VERSION: 5.0\n"
            "targets:\n"
            f"  {name}:\n    type: application\n    platform: iOS\n    deploymentTarget: '17.0'\n"
            "    sources:\n      - path: .\n        excludes:\n          - project.yml\n          - README.md\n"
            "    settings:\n      base:\n"
            f"        PRODUCT_BUNDLE_IDENTIFIER: com.imessageagent.{name}\n"),
        "README.md": "# Generated SwiftUI App\n\nThis folder contains SwiftUI sources and an XcodeGen `project.yml`. Install XcodeGen, run `xcodegen generate`, then choose a signing team before building.\n",
    }
    paths = []
    for filename, content in files.items():
        path = app_dir / filename; path.write_text(content); paths.append(path)
    return paths
